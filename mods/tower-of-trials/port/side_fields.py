#!/usr/bin/env python3
"""Fields ToT adds to the game's structs, kept beside them instead.

On the GameCube ToT grew some of the game's structs (BattleWorkUnit: "Added
fields; only for ToT", with the allocation patched to the new size) or kept
its own values in their padding (BattleWorkUnit.pad_00f). On the PC the game's
structs are the decomp's, allocated by the game at their own size, so each
such field lives in a struct of the mod's own, one per game object, looked up
by the object's address:

    unit->poison_damage   ->   TotSide_BattleWorkUnit(unit).poison_damage

side_fields.txt lists them: `ModStruct field field ...`. The fields'
declarations are taken from ToT's header, so they stay ToT's. A game object
that is freed and allocated again at the same address must start over:
TotSideReset_<Struct>(ptr) (called where ToT set the fields up; manual.py).

Runs on the converted tree before mod_fields.py, on ToT's own names.

  side_fields.py --tot mods/tower-of-trials/tot
"""
import argparse
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def struct_body(tot, name):
    for h in glob.glob(os.path.join(tot, "include", "**", "*.h"), recursive=True):
        text = open(h, encoding="utf-8").read()
        m = re.search(r"\bstruct\s+%s\s*\{(.*?)\n\}\s*;" % re.escape(name), text, re.S)
        if m:
            return m.group(1)
    raise SystemExit("side_fields.py: no struct %s in ToT's headers" % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tot", required=True)
    a = ap.parse_args()
    spec = []
    for line in open(os.path.join(HERE, "side_fields.txt"), encoding="utf-8"):
        line = line.split("#")[0].split()
        if len(line) >= 2:
            spec.append((line[0], line[1:]))

    out = ["// GENERATED by mods/tower-of-trials/port/side_fields.py: the fields ToT adds to the",
           "// game's structs, kept beside each game object (port/side_fields.txt).",
           "#pragma once", "", "#include <ttyd/battle_unit.h>", "", "#include <cstdint>", "#include <unordered_map>", ""]
    fields_of = {}
    for struct, fields in spec:
        body = struct_body(a.tot, struct)
        decls = []
        for f in fields:
            m = re.search(r"^[ \t]*([^;\n]*?\b%s\b\s*(?:\[[^\]]*\])?)\s*;" % re.escape(f), body, re.M)
            if not m:
                raise SystemExit("side_fields.py: no field %s.%s" % (struct, f))
            decls.append(m.group(1).strip())
        fields_of[struct] = fields
        out.append("struct TotSideFields_%s {" % struct)
        out += ["    %s = {};" % d for d in decls]
        out.append("};")
        out.append("inline std::unordered_map<const void*, TotSideFields_%s>& TotSideMap_%s() {" % (struct, struct))
        out.append("    static std::unordered_map<const void*, TotSideFields_%s> map;" % struct)
        out.append("    return map;")
        out.append("}")
        out.append("template <class T> inline TotSideFields_%s& TotSide_%s(T* p) { return TotSideMap_%s()[p]; }"
                   % (struct, struct, struct))
        out.append("template <class T> inline TotSideFields_%s& TotSide_%s(T& p) { return TotSideMap_%s()[&p]; }"
                   % (struct, struct, struct))
        out.append("template <class T> inline void TotSideReset_%s(T* p) { TotSideMap_%s().erase(p); }"
                   % (struct, struct))
        out.append("")
    open(os.path.join(a.tot, "include", "tot_side_fields.h"), "w", encoding="utf-8").write("\n".join(out) + "\n")

    changed = 0
    for src in glob.glob(os.path.join(a.tot, "source", "*.cpp")):
        text = open(src, encoding="utf-8").read()
        new = text
        for struct, fields in fields_of.items():
            names = "|".join(map(re.escape, fields))
            access = re.compile(r"((?:\b\w+(?:\[[^\]]*\])?)(?:(?:->|\.)\w+(?:\[[^\]]*\])?)*?)(->|\.)(%s)\b" % names)
            new = access.sub(lambda m: "TotSide_%s(%s).%s" % (struct, m.group(1), m.group(3)), new)
        if new != text:
            if '#include "tot_side_fields.h"' not in new:
                new = '#include "tot_side_fields.h"\n' + new
            open(src, "w", encoding="utf-8").write(new)
            changed += 1
    print("side_fields.py: %d structs, %d files" % (len(fields_of), changed))


if __name__ == "__main__":
    main()
