#!/usr/bin/env python3
"""Move the part of the pause menu's work that ToT re-lays-out into a struct
of the mod's own.

ToT's WinPauseMenu (include/ttyd/win_root.h) is the game's WindowWork with
0x0d68..0x1030 laid out anew ("Fields from 0xe14 ~ 0x1030 are altered from
vanilla"): its log, badge-log, recipe-log, move, records and achievement
menus, which only ToT's code (tot_window_log.cpp and friends, in place of the
game's log menu) reads and writes. On the GameCube that was free memory
inside the game's buffer; on the PC WindowWork has the decomp's layout,
which has none of those fields, and laying ToT's over it by offset would
clobber the game's. So those fields live in TotPauseMenuExtra, one per
pause menu (zeroed when the game's menu work changes, as the game zeroes its
own), and every `x->field` / `x.field` of them in ToT's sources becomes
`TotPauseExtra(x).field`.

Runs on the converted tree before mod_fields.py, on ToT's own names.

  pause_extra.py --tot mods/tower-of-trials/tot
"""
import argparse
import glob
import os
import re

FIRST, LAST = "log_menu_state", "unused_0x101c"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tot", required=True)
    a = ap.parse_args()
    hdr = os.path.join(a.tot, "include", "ttyd", "win_root.h")
    text = open(hdr, encoding="utf-8").read()
    body = re.search(r"struct WinPauseMenu\s*\{(.*?)\n\};", text, re.S).group(1)
    lines = body.splitlines()
    start = next(i for i, ln in enumerate(lines) if re.search(r"\b%s\b" % FIRST, ln))
    end = next(i for i, ln in enumerate(lines) if re.search(r"\b%s\b" % LAST, ln))
    decls = [ln for ln in lines[start:end + 1]]
    fields = []
    for ln in decls:
        m = re.match(r"\s*[\w:<>\*\s]+?\b(\w+)\s*(\[[^\]]*\])?\s*;", ln)
        if m:
            fields.append(m.group(1))

    out = os.path.join(a.tot, "include", "tot_pause_extra.h")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// GENERATED by mods/tower-of-trials/port/pause_extra.py from ToT's win_root.h:\n")
        f.write("// the pause menu fields ToT lays out anew (0x0d68..0x1030 on the GameCube).\n")
        f.write("#pragma once\n\n#include <ttyd/win_root.h>\n\n#include <cstdint>\n#include <cstring>\n\n")
        f.write("struct TotPauseMenuExtra {\n")
        for ln in decls:
            f.write(re.sub(r"\s*//\s*0x[0-9a-fA-F]+\s*$", "", ln.replace("WinLogSubmenuInfo",
                    "::ttyd::win_root::WinLogSubmenuInfo")) + "\n")
        f.write("};\n\n")
        f.write("// The extra fields of the pause menu work `menu` (one menu at a time:\n")
        f.write("// zeroed when the game's menu work is a new one).\n")
        f.write("template <class T>\ninline TotPauseMenuExtra& TotPauseExtra(T* menu) {\n")
        f.write("    static TotPauseMenuExtra extra;\n    static const void* owner = nullptr;\n")
        f.write("    if (owner != static_cast<const void*>(menu)) {\n")
        f.write("        std::memset(&extra, 0, sizeof(extra));\n        owner = menu;\n    }\n")
        f.write("    return extra;\n}\n")
        f.write("template <class T>\ninline TotPauseMenuExtra& TotPauseExtra(T& menu) { return TotPauseExtra(&menu); }\n")

    names = "|".join(map(re.escape, fields))
    access = re.compile(r"((?:\b\w+(?:\[[^\]]*\])?)(?:(?:->|\.)\w+(?:\[[^\]]*\])?)*?)(->|\.)(%s)\b" % names)
    changed = 0
    for src in glob.glob(os.path.join(a.tot, "source", "*.cpp")):
        s = open(src, encoding="utf-8").read()
        new = access.sub(lambda m: "TotPauseExtra(%s).%s" % (m.group(1), m.group(3)), s)
        if new != s:
            if '#include "tot_pause_extra.h"' not in new:
                new = '#include "tot_pause_extra.h"\n' + new
            open(src, "w", encoding="utf-8").write(new)
            changed += 1
    print("pause_extra.py: %d fields moved; %d files" % (len(fields), changed))


if __name__ == "__main__":
    main()
