#!/usr/bin/env python3
"""Pointer-taking overloads for the game functions ToT calls with small
structs by address.

The GameCube's ABI passed a struct argument (a Vec, a GXColor) by address,
so ToT declares and calls `winFontSet(&pos, &scale, &color, fmt, ...)`; the
decomp declares it as C does, `winFontSet(Vec pos, Vec scale, GXColor color,
const char* fmt, ...)`. ttyd_mod/game_loose.h converts such calls for most
functions, but not variadic ones (winFontSet...) or those reached through a
`using ::name;` in a namespace of ToT's. This writes, for every function a
converted ToT header brings into a namespace with `using ::name;` and whose
decomp prototype takes one of those structs by value, a template overload in
that namespace taking pointers there:

    namespace ttyd::win_main {
    template <class... A> inline auto winFontSet(const Vec* a0, const Vec* a1, const GXColor* a2, A... a)
        { return ::winFontSet(*a0, *a1, *a2, a...); }
    }

  byvalue.py --tot mods/tower-of-trials/tot --out tot/generated/tot_byvalue.h
"""
import argparse
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
BYVALUE = ("Vec", "GXColor", "GXColorS10", "Vec2", "Quaternion")
PROTO = re.compile(r"^\s*(?:extern\s+)?[\w\s\*]+?\b(\w+)\s*\(([^;{]*?)\)\s*;", re.M)


def decomp_prototypes():
    out = {}
    for path in glob.glob(os.path.join(ROOT, "include", "**", "*.h"), recursive=True):
        text = open(path, encoding="utf-8", errors="replace").read()
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
        for m in PROTO.finditer(text):
            params = [p.strip() for p in m.group(2).replace("\n", " ").split(",")]
            out.setdefault(m.group(1), params)
    return out


def struct_of(param):
    """The by-value struct a parameter is, or None."""
    p = re.sub(r"\b(?:const|struct)\b", "", param).strip()
    if "*" in p or "[" in p:
        return None
    t = p.split()[0] if p.split() else ""
    return t if t in BYVALUE else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tot", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    protos = decomp_prototypes()
    per_ns = {}
    for path in glob.glob(os.path.join(a.tot, "include", "**", "*.h"), recursive=True):
        text = open(path, encoding="utf-8").read()
        for ns in re.finditer(r"namespace\s+(ttyd::[\w:]+)\s*\{", text):
            depth, i = 1, ns.end()
            while i < len(text) and depth:
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            for u in re.finditer(r"using\s+::(\w+)\s*;", text[ns.end():i]):
                per_ns.setdefault(ns.group(1), set()).add(u.group(1))
    lines = ["// GENERATED by mods/tower-of-trials/port/byvalue.py: ToT's struct-by-address calls,",
             "// onto the decomp's by-value prototypes.", "#pragma once", "",
             '#include "tot_byvalue_helpers.h"', ""]
    count = 0
    for ns in sorted(per_ns):
        body = []
        for name in sorted(per_ns[ns]):
            params = protos.get(name)
            if not params or params == ["void"]:
                continue
            variadic = params[-1] == "..."
            fixed = params[:-1] if variadic else params
            structs = [struct_of(p) for p in fixed]
            if not any(structs):
                continue
            # the arguments up to the last struct are spelled; the rest pass through
            last = max(i for i, s in enumerate(structs) if s)
            decl, call, tparams = [], [], []
            for i in range(last + 1):
                if structs[i]:
                    tparams.append("class P%d" % i)
                    decl.append("const P%d* a%d" % (i, i))
                    call.append("tot_port::ByValue<%s>(a%d)" % (structs[i], i))
                else:
                    t = re.sub(r"\s*\b\w+\s*$", "", fixed[i]) if len(fixed[i].split()) > 1 else fixed[i]
                    decl.append("%s a%d" % (t, i))
                    call.append("a%d" % i)
            body.append("template <%s, class... A> inline auto %s(%s, A... a) { return ::%s(%s, a...); }"
                        % (", ".join(tparams), name, ", ".join(decl), name, ", ".join(call)))
            count += 1
        if body:
            lines.append("namespace %s {" % ns)
            lines += body
            lines.append("}")
            lines.append("")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("byvalue.py: %d overloads" % count)


if __name__ == "__main__":
    main()
